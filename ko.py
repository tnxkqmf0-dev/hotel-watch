def _hira2kata(s):
    return "".join(chr(ord(c) + 0x60) if "ぁ" <= c <= "ゖ" else c for c in s)


def _set_vowel(syl, jamo):
    code = ord(syl) - 0xAC00
    if not (0 <= code < 11172):
        return syl
    cho, _, jong = code // 588, (code % 588) // 28, code % 28
    if jamo in ("ㅑ", "ㅠ", "ㅛ") and syl[-1] in "시지치":   # 샤/쥬/쵸 → 샤/주/초
        jamo = {"ㅑ": "ㅏ", "ㅠ": "ㅜ", "ㅛ": "ㅗ"}[jamo]
    return chr(0xAC00 + cho * 588 + _JUNG.index(jamo) * 28 + jong)


def _add_batchim(syl, idx):
    code = ord(syl) - 0xAC00
    if not (0 <= code < 11172) or code % 28:
        return syl
    return chr(ord(syl) + idx)


def kana_to_hangul(s):
    s = _hira2kata(s)
    out = []
    for c in s:
        if c in _KANA:
            h = _KANA[c]
            if h == "ㄴ" and out:
                out[-1] = _add_batchim(out[-1], 4)
            elif h != "ㄴ":
                out.append(h)
        elif c in _SMALL and out:
            out[-1] = _set_vowel(out[-1], _SMALL[c])
        elif c in "ッっ" and out:
            out[-1] = _add_batchim(out[-1], 19)  # ㅅ 받침
        elif c == "ー":
            continue
        else:
            out.append(c)
    return "".join(out)


def _tidy(s):
    s = unicodedata.normalize("NFKC", s)            # 전각 영문·숫자 → 반각
    s = s.replace("　", " ")
    return s


def translate(s):
    """단어 사전으로 바꾸고, 남은 가나는 소리대로."""
    s = _tidy(s or "")
    s = re.sub(r"(\d+(?:\.\d+)?)\s*[畳帖]", r" 다다미 \1장 ", s)
    s = re.sub(r"(\d)\s*台", r"\1대", s)
    s = re.sub(r"(\d)\s*部屋", r"\1실", s)
    s = re.sub(r"[★☆◆◇●○]+", " ", s).replace("・", " ")
    s = _WORD_RE.sub(lambda m: f" {WORDS[m.group(0)]} ", s)
    s = re.sub(r"[ァ-ヺー]+|[ぁ-ゖ]+", lambda m: f" {kana_to_hangul(m.group(0))} ", s)
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"(\d) (대|세트|명|방|실|층|호관|인|칸|㎡)", r"\1\2", s)   # 숫자+단위 붙이기
    s = re.sub(r"\s*([)）】」』>＞!！、。+])", r"\1", s)                # 닫는 기호 앞 공백 제거
    s = re.sub(r"([(（【「『<＜+])\s*", r"\1", s)                       # 여는 기호 뒤 공백 제거
    s = re.sub(r"다다미방 다다미 (\S+장)", r"다다미방 \1", s)
    s = s.strip(" ・･-－")
    return s


def hotel_name(no, name):
    """(한국어 이름, 자동번역 여부)"""
    if str(no) in HOTEL_KO:
        return HOTEL_KO[str(no)], False
    clean = re.sub(r"[（(][^）)]*(年|オープン|リニューアル)[^）)]*[）)]", "", _tidy(name))
    clean = re.sub(r"[〈〉<>]", " ", clean)
    return translate(clean), True


def room_name(label):
    return translate(label)


def station(st):
    st = re.sub(r"[（(].*?[）)]", "", st or "").strip()
    if not st:
        return "", ""
    if st in STATION_KO:
        return STATION_KO[st]
    return translate(st) + "역", ""


def ward(w):
    return WARD_KO.get(w or "", translate(w or ""))


